"""Embed the FAQ chunks with Ollama and write db/init/02-seed.sql.

Re-run after editing faq_chunks.json:

    ollama pull nomic-embed-text
    python3 db/seed/generate_seed.py

Only the standard library is used. OLLAMA_HOST overrides the default http://localhost:11434.
"""

import json
import os
import urllib.request
from pathlib import Path

MODEL = "nomic-embed-text"
DIMENSIONS = 768
SEED_DIR = Path(__file__).resolve().parent
CHUNKS = SEED_DIR / "faq_chunks.json"
OUTPUT = SEED_DIR.parent / "init" / "02-seed.sql"
OLLAMA_HOST = os.environ.get("OLLAMA_HOST", "http://localhost:11434")


def embed(texts):
    # nomic-embed-text expects a task prefix; queries must use "search_query: "
    body = json.dumps({"model": MODEL, "input": [f"search_document: {t}" for t in texts]}).encode()
    request = urllib.request.Request(f"{OLLAMA_HOST}/api/embed", body, {"Content-Type": "application/json"})
    with urllib.request.urlopen(request) as response:
        return json.load(response)["embeddings"]


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def main():
    chunks = json.loads(CHUNKS.read_text())
    embeddings = embed([f"{c['title']}\n{c['content']}" for c in chunks])

    rows = []
    for chunk, vector in zip(chunks, embeddings):
        if len(vector) != DIMENSIONS:
            raise SystemExit(f"expected {DIMENSIONS} dimensions, got {len(vector)}")
        literal = "[" + ",".join(f"{x:.6f}" for x in vector) + "]"
        rows.append(f"({sql_text(chunk['category'])}, {sql_text(chunk['title'])}, "
                    f"{sql_text(chunk['content'])}, '{literal}')")

    OUTPUT.write_text(
        f"-- Generated by db/seed/generate_seed.py from faq_chunks.json ({MODEL}). Do not edit by hand.\n\n"
        "INSERT INTO faq_chunks (category, title, content, embedding) VALUES\n"
        + ",\n".join(rows) + ";\n"
    )
    print(f"wrote {len(rows)} chunks to {OUTPUT.relative_to(SEED_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
